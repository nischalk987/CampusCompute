#!/usr/bin/env python3
"""Compile genuine S01-S24 terminal screenshots into a labeled evidence PDF."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from PIL import Image
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    Image as RLImage,
    KeepTogether,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
)

CAPTIONS = [
    ("Clean source build", "Run make clean && make build. Show the real compiler output and successful build completion."),
    ("Automated test suite", "Run make test and show the actual final test result."),
    ("Application main menu", "Launch the integrated CLI and show its real menu."),
    ("FR1 valid job creation", "Show valid job details being accepted and the resulting job status."),
    ("FR1 invalid job input", "Show an invalid job ID or malformed input rejected by the program."),
    ("FR2 FCFS scheduling", "Show input jobs, FCFS execution order/timeline, and calculated metrics."),
    ("FR2 Round Robin scheduling", "Show input jobs, time quantum, execution order, and calculated metrics."),
    ("FR2 Priority scheduling", "Show input jobs, priorities, tie handling, and calculated metrics."),
    ("FR3 producer-consumer", "Show real producer/consumer activity and orderly thread termination."),
    ("FR3 activity log", "Show the actual log output/file generated by the producer-consumer scenario."),
    ("FR4 shared-memory exchange", "Show writer/reader message exchange and acknowledgement."),
    ("FR4 IPC cleanup", "Show that the project's named IPC resources are absent after the application exits."),
    ("FR5 safe Banker state", "Show the test data and computed safe sequence."),
    ("FR5 unsafe Banker state", "Show an unsafe-state result for a deliberately unsafe input."),
    ("FR6 normal worker", "Show parent/child execution and the normal child exit status."),
    ("FR6 simulated worker failure", "Show the controlled failure and its detected exit status."),
    ("FR7 resource limit", "Show the applied resource limit and its observed effect."),
    ("FR7 resource cleanup", "Show descriptors/resources released by the scenario."),
    ("FR8 invalid menu input", "Show invalid menu input handled with a useful error or re-prompt."),
    ("FR8 EOF handling", "Show graceful handling of end-of-input."),
    ("Integrated CLI flow", "Show a complete real CLI path through a selected feature and back to the menu/exit."),
    ("Backend health/API", "If the backend is configured, show its real health endpoint response."),
    ("Frontend production build", "If Node dependencies are configured, show npm run build succeeding."),
    ("Final clean verification", "Show the final repository revision and clean verification state."),
]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--srn", required=True, help="Verified student SRN used in the PDF filename/title")
    parser.add_argument("--input-dir", type=Path, default=Path("evidence/screenshots"))
    parser.add_argument("--output", type=Path, help="Output PDF path (default: <SRN>.pdf)")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    srn = args.srn.strip()
    if not re.fullmatch(r"[A-Za-z0-9_-]{4,32}", srn):
        print("ERROR: SRN must be 4-32 letters, digits, '_' or '-'.", file=sys.stderr)
        return 2

    screenshots: list[tuple[str, str, Path, int, int]] = []
    missing: list[str] = []
    for index, (heading, caption) in enumerate(CAPTIONS, start=1):
        code = f"S{index:02d}"
        path = args.input_dir / f"{code}.png"
        if not path.is_file():
            missing.append(str(path))
            continue
        try:
            with Image.open(path) as image:
                image.verify()
            with Image.open(path) as image:
                width, height = image.size
                if width < 320 or height < 200:
                    raise ValueError(f"image too small ({width}x{height})")
            screenshots.append((code, heading, path, width, height))
        except Exception as exc:
            print(f"ERROR: {path}: {exc}", file=sys.stderr)
            return 2

    if missing:
        print("ERROR: refusing to create an incomplete evidence PDF. Missing screenshots:", file=sys.stderr)
        for path in missing:
            print(f"  - {path}", file=sys.stderr)
        print(f"Captured {len(screenshots)}/24 screenshots.", file=sys.stderr)
        return 2

    output = args.output or Path(f"{srn}.pdf")
    output.parent.mkdir(parents=True, exist_ok=True)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "EvidenceTitle", parent=styles["Title"], alignment=TA_CENTER,
        fontSize=18, leading=22, spaceAfter=8 * mm,
    )
    heading_style = ParagraphStyle(
        "EvidenceHeading", parent=styles["Heading2"], fontSize=13,
        leading=16, spaceAfter=3 * mm,
    )
    caption_style = ParagraphStyle(
        "EvidenceCaption", parent=styles["BodyText"], fontSize=9,
        leading=12, textColor=colors.HexColor("#333333"),
    )
    doc = SimpleDocTemplate(
        str(output), pagesize=A4,
        rightMargin=15 * mm, leftMargin=15 * mm,
        topMargin=14 * mm, bottomMargin=14 * mm,
        title=f"CampusCompute Evidence - {srn}",
        author="CampusCompute",
    )
    story = [
        Paragraph("CampusCompute — Project Evidence", title_style),
        Paragraph(f"<b>Student SRN:</b> {srn}", styles["BodyText"]),
        Paragraph("<b>Evidence set:</b> S01–S24 · Genuine terminal/application captures", styles["BodyText"]),
        Spacer(1, 5 * mm),
        Paragraph(
            "Each page contains the supplied screenshot and its scenario description. "
            "Screenshots are included as provided; this tool does not create or alter terminal output.",
            caption_style,
        ),
        PageBreak(),
    ]

    usable_w = A4[0] - 30 * mm
    usable_h = A4[1] - 28 * mm - 24 * mm
    for index, (code, heading, path, width, height) in enumerate(screenshots):
        _, caption = CAPTIONS[index]
        scale = min(usable_w / width, (usable_h - 26 * mm) / height)
        picture = RLImage(str(path), width=width * scale, height=height * scale)
        story.append(KeepTogether([
            Paragraph(f"{code} — {heading}", heading_style),
            Paragraph(caption, caption_style),
            Spacer(1, 5 * mm),
            picture,
        ]))
        if index != len(screenshots) - 1:
            story.append(PageBreak())

    def footer(canvas, document):
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.grey)
        canvas.drawString(15 * mm, 8 * mm, f"CampusCompute Evidence · {srn}")
        canvas.drawRightString(A4[0] - 15 * mm, 8 * mm, f"Page {document.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    print(f"Created {output} with {len(screenshots)} supplied screenshots.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
